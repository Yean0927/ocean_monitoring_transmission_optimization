"""Recalculate byte-weighted delivery metrics from saved per-file results.

This is a post-hoc observation cutoff, not a new simulation run.
"""

import argparse
import csv
import sys
from pathlib import Path


VARIANTS = ("FULL", "WO_PROTOCOL", "WO_COMPRESSION", "WO_CACHE", "BASELINE")
RESULTS = Path(__file__).resolve().parent / "results"


def calculate(variant: str, horizon: float) -> dict:
    with (RESULTS / f"{variant}.csv").open(newline="") as source:
        rows = list(csv.DictReader(source))

    if any(float(row["first_s"]) > horizon for row in rows):
        raise ValueError("The cutoff precedes some source generation; denominator must be rebuilt")

    generated = sum(int(row["generated_raw_bytes"]) for row in rows)
    delivered = [
        row for row in rows
        if row["status"] == "delivered" and float(row["decoded_s"]) <= horizon
    ]
    permanently_lost = [
        row for row in rows
        if row["status"] in ("source_dropped", "cache_evicted")
        and float(row["ready_s"]) <= horizon
    ]
    delivered_bytes = sum(int(row["generated_raw_bytes"]) for row in delivered)
    lost_bytes = sum(int(row["generated_raw_bytes"]) for row in permanently_lost)
    pending_bytes = generated - delivered_bytes - lost_bytes
    if pending_bytes < 0:
        raise ValueError("Delivery and loss accounting exceeds generated bytes")
    byte_seconds = sum(
        int(row["generated_raw_bytes"])
        * (
            min(float(row["decoded_s"]), horizon) - float(row["first_s"])
            if row["status"] == "delivered"
            else horizon - float(row["first_s"])
        )
        for row in rows
    )
    return {
        "variant": variant,
        "horizon_s": horizon,
        "generated_raw_bytes": generated,
        "delivered_raw_equivalent_bytes": delivered_bytes,
        "completion_pct": 100 * delivered_bytes / generated,
        "confirmed_permanent_loss_raw_bytes": lost_bytes,
        "confirmed_permanent_loss_pct": 100 * lost_bytes / generated,
        "pending_raw_bytes": pending_bytes,
        "pending_pct": 100 * pending_bytes / generated,
        "restricted_mean_delivery_time_s": byte_seconds / generated,
        "completed_files": len(delivered),
        "confirmed_lost_files": len(permanently_lost),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--horizon", type=float, default=3600)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    rows = [calculate(variant, args.horizon) for variant in VARIANTS]
    if args.output:
        with args.output.open("w", newline="") as target:
            writer = csv.DictWriter(target, fieldnames=rows[0].keys())
            writer.writeheader()
            writer.writerows(rows)
    else:
        writer = csv.DictWriter(sys.stdout, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)


if __name__ == "__main__":
    main()
