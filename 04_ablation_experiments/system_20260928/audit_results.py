"""Audit one seed's byte accounting, event order and protocol decisions."""
from __future__ import annotations
import argparse
import csv
from functools import lru_cache
import json
from pathlib import Path
import re
from collections import Counter

HERE = Path(__file__).resolve().parent
VARIANTS = ('FULL', 'WO_PROTOCOL', 'WO_COMPRESSION', 'WO_CACHE', 'BASELINE',
            'ADD_PROTOCOL', 'ADD_COMPRESSION', 'ADD_CACHE')


def read_csv(path):
    with Path(path).open(newline='') as handle:
        return list(csv.DictReader(handle))


@lru_cache(maxsize=4)
def input_context(prepared):
    definitions = json.loads((prepared / 'files.json').read_text())
    config = json.loads((prepared / 'run-config.json').read_text())
    generated = Counter()
    with (prepared / 'events.tsv').open(newline='') as handle:
        for event in csv.DictReader(handle, delimiter='\t'):
            if float(event['time']) < config['duration_s']:
                generated[int(event['id'])] += int(event['length'])
    return definitions, config, generated


def audit_seed(prepared, results):
    definitions, config, event_bytes = input_context(Path(prepared).resolve())
    horizon = config['duration_s'] + config['drain_s']
    summaries = {row['variant']: row for row in read_csv(results / 'summary.csv')}
    assert set(summaries) == set(VARIANTS), 'Missing or unexpected summary variants'
    report = {}
    for variant in VARIANTS:
        rows = read_csv(results / f'{variant}.csv')
        assert len(rows) == len(definitions), (variant, 'file count')
        assert [int(r['id']) for r in rows] == list(range(len(definitions)))
        delivered = [r for r in rows if r['status'] == 'delivered']
        dropped = [r for r in rows if r['status'] in ('source_dropped', 'cache_evicted')]
        for row, item in zip(rows, definitions):
            assert int(row['generated_raw_bytes']) == event_bytes[item['id']], (variant, row['id'], 'generated bytes')
            assert int(row['raw_file_bytes']) == item['raw_bytes']
            assert int(row['stream']) == item['stream']
            assert 0 <= int(row['arrived_raw_bytes']) <= int(row['generated_raw_bytes'])
        for row in delivered:
            assert int(row['raw_file_bytes']) == int(row['generated_raw_bytes']) == int(row['arrived_raw_bytes'])
            times = [float(row[k]) for k in ('first_s','assembled_s','ready_s','tx_start_s','received_s','decoded_s')]
            assert all(a <= b + 1e-8 for a, b in zip(times, times[1:])), (variant, row['id'], times)
            assert times[-1] <= horizon + 1e-8
        for decision in read_csv(results / f'{variant}.csv.decisions.csv'):
            item = definitions[int(decision['id'])]
            static = variant in ('WO_PROTOCOL','BASELINE','ADD_COMPRESSION','ADD_CACHE')
            raw = variant in ('WO_COMPRESSION','ADD_PROTOCOL','ADD_CACHE')
            expected = 2 if static else int(item['raw_choices' if raw else 'comp_choices'][int(decision['state_index'])])
            assert int(decision['protocol']) == expected, (variant, decision)
            assert float(decision['time_s']) <= horizon
        g = sum(int(r['generated_raw_bytes']) for r in rows)
        d = sum(int(r['raw_file_bytes']) for r in delivered)
        loss = sum(int(r['generated_raw_bytes']) for r in dropped)
        pending = g - d - loss
        assert pending >= 0 and g == sum(config['generated_raw_bytes'])
        byte_seconds = sum(int(r['generated_raw_bytes']) *
            ((float(r['decoded_s']) if r['status']=='delivered' else horizon) - float(r['first_s'])) for r in rows)
        calculated = dict(generated_raw_bytes=g, delivered_raw_equivalent_bytes=d,
                          permanently_dropped_raw_equivalent_bytes=loss, pending_raw_bytes=pending,
                          success_delivery_pct=100*d/g, loss_pct=100*loss/g,
                          pending_pct=100*pending/g, restricted_mean_delivery_time_s=byte_seconds/g)
        for key, value in calculated.items():
            assert abs(float(summaries[variant][key]) - value) <= 1e-7, (variant, key)
        metrics = json.loads((results / f'{variant}.csv.metrics.json').read_text())
        assert metrics['peak_queue_bytes'] <= config['cache_bytes']
        if variant in ('WO_CACHE','BASELINE','ADD_PROTOCOL','ADD_COMPRESSION'):
            assert metrics['peak_queue_bytes'] == 0
        log = (results / f'{variant}.log').read_text()
        assert not re.search(r'QUIC_ABORT|PAYLOAD_MISMATCH|NS_FATAL|Traceback', log), (variant, 'runtime error')
        stalls = [r['id'] for r in rows if r['status'] in ('in_service','in_transport')
                  and float(r['tx_start_s']) >= 0 and horizon - float(r['tx_start_s']) >= 600]
        report[variant] = dict(file_rows=len(rows), status_counts=dict(Counter(r['status'] for r in rows)),
                               **calculated, accounting_and_event_order='PASS', protocol_predictions='PASS',
                               summary_matches_trace='PASS', long_transport_item_ids=stalls)
    assert len(read_csv(results / 'by-stream.csv')) == 48
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prepared', type=Path, default=HERE/'prepared')
    parser.add_argument('--results', type=Path, default=HERE.parent/'results/final_five_seeds/seed-31')
    parser.add_argument('--output', type=Path)
    parser.add_argument('--fail-on-stall', action='store_true', help='Treat an item active for >=600 s as a failure; otherwise report it for diagnosis.')
    args = parser.parse_args()
    report = audit_seed(args.prepared, args.results)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n')
    flagged = [v for v, r in report.items() if r['long_transport_item_ids']]
    if args.fail_on_stall:
        assert not flagged, f'Long transport items in {flagged}'
    print(json.dumps(dict(status='PASS', variants=len(report), long_transport_variants=flagged), ensure_ascii=False))


if __name__ == '__main__':
    main()
